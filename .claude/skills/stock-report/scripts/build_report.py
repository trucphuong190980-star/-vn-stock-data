PCT = re.compile(r"\d+(?:[.,]\d+)?\s*%")
LINE_COLORS = ["#024AD8", "#0096D6", "#013BAC"]


def now_vn() -> str:
    return datetime.now(VN).replace(microsecond=0).isoformat()


def check_picks(picks, top) -> list:
    errs = []
    if not isinstance(picks, dict) or not isinstance(picks.get("summary"), str) or not isinstance(picks.get("picks"), list):
        return ['picks.json phải có dạng {"summary": "...", "picks": [{"ticker": "...", "reason": "..."}]}']
    if len(picks["summary"]) > 300:
        errs.append(f"summary dài {len(picks['summary'])} ký tự, tối đa 300")
    if PCT.search(picks["summary"]):
        errs.append("summary có con số phần trăm; bỏ số, chỉ diễn giải")
    got = [p.get("ticker") for p in picks["picks"] if isinstance(p, dict)]
    if got != top:
        errs.append(f"picks phải đúng các mã {top} theo thứ tự, đang có {got}")
    for p in picks["picks"]:
        r = p.get("reason", "") if isinstance(p, dict) else ""
        if not 20 <= len(r) <= 400:
            errs.append(f"{p.get('ticker')}: lý do dài {len(r)} ký tự, cần 20–400")
        if PCT.search(r):
            errs.append(f"{p.get('ticker')}: lý do có con số phần trăm; số đã có trong bảng, chỉ diễn giải")
    return errs


def chart_svg(series, highlight, dates) -> str:
    W, H, PL, PR, PT, PB = 720, 250, 44, 86, 14, 28
    vals = [v for s in series.values() for v in s if v is not None]
    lo, hi = min(vals + [100]), max(vals + [100])
    pad = (hi - lo) * 0.08 or 1
    lo, hi = lo - pad, hi + pad
    n = max(len(dates) - 1, 1)
    x = lambda i: PL + (W - PL - PR) * i / n
    y = lambda v: PT + (H - PT - PB) * (1 - (v - lo) / (hi - lo))
    out = [f'<svg viewBox="0 0 {W} {H}" width="100%" role="img" aria-label="chart">']
    for k in range(5):
        v = lo + (hi - lo) * k / 4
        out.append(f'<line x1="{PL}" x2="{W - PR}" y1="{y(v):.1f}" y2="{y(v):.1f}" stroke="#E8E8E8"/>'
                   f'<text x="{PL - 6}" y="{y(v) + 4:.1f}" text-anchor="end" font-size="10" fill="#6B6B6B">{v:.0f}</text>')
    out.append(f'<line x1="{PL}" x2="{W - PR}" y1="{y(100):.1f}" y2="{y(100):.1f}" stroke="#9A9A9A" stroke-dasharray="4 3"/>')
    out.append(f'<text x="{PL}" y="{H - 8}" font-size="10" fill="#6B6B6B">{dates[0]}</text>'
               f'<text x="{W - PR}" y="{H - 8}" text-anchor="end" font-size="10" fill="#6B6B6B">{dates[-1]}</text>')

    def path(s):
        pts = [(x(i), y(v)) for i, v in enumerate(s) if v is not None]
        return " ".join(f"{px:.1f},{py:.1f}" for px, py in pts), pts

    for t, s in series.items():
        if t not in highlight:
            d, _ = path(s)
            out.append(f'<polyline points="{d}" fill="none" stroke="#C9CED6" stroke-width="1.4"/>')
    for i, t in enumerate(highlight):
        d, pts = path(series[t])
        c = LINE_COLORS[i % len(LINE_COLORS)]
        out.append(f'<polyline points="{d}" fill="none" stroke="{c}" stroke-width="2.4"/>')
        if pts:
            ex, ey = pts[-1]
            out.append(f'<circle cx="{ex:.1f}" cy="{ey:.1f}" r="3.5" fill="{c}"/>'
                       f'<text x="{ex + 7:.1f}" y="{ey + 4:.1f}" font-size="11" font-weight="700" fill="{c}">{html.escape(t)}</text>')
    out.append("</svg>")
    return "".join(out)


def render(m, picks, run, t) -> str:
    e = html.escape
    by = {r["ticker"]: r for r in m["tickers"]}
    trend = {"up": t["t_up"], "down": t["t_down"], "flat": t["t_flat"]}
    group = {"top": t["g_top"], "watch": t["g_watch"], "avoid": t["g_avoid"]}
    mk = m["market"]
    cards = []
    for i, p in enumerate(picks["picks"]):
        r = by[p["ticker"]]
        cards.append(f'<div class="card"><div class="ch"><span class="no">{i + 1}</span><b>{e(r["ticker"])}</b>'
                     f'<span class="kv">{t["ret"]} <b class="{"pos" if r["return_pct"] >= 0 else "neg"}">{r["return_pct"]:+.1f}%</b>'
                     f' · {t["vol"]} <b>{r["volatility_pct"]:.1f}%</b></span></div><p>{e(p["reason"])}</p></div>')
    rows = []
    for r in m["tickers"]:
        rows.append(f'<tr class="g-{r["group"]}"><td><b>{e(r["ticker"])}</b></td><td class="n">{r["close"]:,.2f}</td>'
                    f'<td class="n {"pos" if r["return_pct"] >= 0 else "neg"}">{r["return_pct"]:+.1f}%</td>'
                    f'<td class="n">{r["volatility_pct"]:.1f}%</td><td>{trend[r["trend"]]}</td>'
                    f'<td class="n">{r["volume_ratio"]:.2f}</td><td><span class="pill p-{r["group"]}">{group[r["group"]]}</span></td></tr>')
    notes = "".join(f"<li>{e(f['detail'])}</li>" for f in run.get("flags", []))
    notes_html = f'<div class="notes"><b>{t["notes"]}</b><ul>{notes}</ul></div>' if notes else ""
