def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True, help="thư mục lần chạy, ví dụ runs/2026-10-29")
    ap.add_argument("--root", default=".")
    a = ap.parse_args()
    root = Path(a.root)
    run_dir = Path(a.run) if Path(a.run).is_absolute() else root / a.run
    m = json.loads((run_dir / "metrics.json").read_text(encoding="utf-8"))
    run_path = run_dir / "run.json"
    run = json.loads(run_path.read_text(encoding="utf-8"))
    t = L.get(m.get("language", "vi"), L["vi"])

    picks_path = run_dir / "picks.json"
    try:
        picks = json.loads(picks_path.read_text(encoding="utf-8"))
        errs = check_picks(picks, m["top"])
    except FileNotFoundError:
        errs = ["chưa có picks.json"]
    except json.JSONDecodeError as ex:
        errs = [f"picks.json không phải JSON hợp lệ: {ex}"]

    steps = {s["step"]: s for s in run["steps"]}
    if errs:
        steps["analyze"].update(status="failed", note="; ".join(errs))
        steps["report"].update(status="not_run")
        run.update(status="failed", updated_at=now_vn())
        run_path.write_text(json.dumps(run, ensure_ascii=False, indent=2), encoding="utf-8")
        print("LỖI picks.json:")
        for x in errs:
            print(" -", x)
        return 2

    out = root / "reports" / f"stock_report_{m['run_id']}.html"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(m, picks, run, t), encoding="utf-8")
    steps["analyze"].update(status="ok", note=f"lý do cho {', '.join(m['top'])}")
    steps["report"].update(status="ok", note=out.relative_to(root).as_posix())
    run.update(status="succeeded", updated_at=now_vn(), outputs=[out.relative_to(root).as_posix()])
    run_path.write_text(json.dumps(run, ensure_ascii=False, indent=2), encoding="utf-8")
    (root / "logs").mkdir(exist_ok=True)
    (root / "logs" / "last_analyzed.txt").write_text(m["data_date"] + "\n", encoding="utf-8")
    print(json.dumps({"status": "succeeded", "report": out.relative_to(root).as_posix()}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
