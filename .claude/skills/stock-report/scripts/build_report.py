"""build_report.py — bước "report" của workflow.yaml (SCRIPT).

Đọc runs/{ngày}/metrics.json (số do check_and_measure.py tính) và picks.json (lý do do AI viết), kiểm picks.json theo
luật của skill stock-picks, dựng report HTML một trang tự chứa, rồi cập nhật run.json và logs/last_analyzed.txt.

    python .claude/skills/stock-report/scripts/build_report.py --run runs/2026-10-29 [--root .]

Exit 2 khi picks.json sai luật: in rõ lỗi, run.json ghi failed. Sửa picks.json rồi chạy lại.
"""
